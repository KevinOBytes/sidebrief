import Foundation
import AppKit
import CoreGraphics

public final class MeetingExportService: @unchecked Sendable {
    public static let shared = MeetingExportService()

    public init() {}

    // MARK: - Plain Text (.txt) Export

    public func generatePlainText(
        meeting: Meeting,
        segments: [TranscriptSegment],
        summary: MeetingSummary? = nil
    ) -> String {
        var txt = "================================================================================\n"
        txt += "SIDEBRIEF MEETING JOURNAL\n"
        txt += "Title:    \(meeting.title.isEmpty ? "Meeting Transcript" : meeting.title)\n"
        let dateStr = (meeting.actualStartTime ?? meeting.createdAt).formatted(date: .long, time: .shortened)
        txt += "Date:     \(dateStr)\n"
        if let start = meeting.actualStartTime, let end = meeting.actualEndTime {
            let s = Int(end.timeIntervalSince(start))
            txt += "Duration: \(s / 60)m \(s % 60)s\n"
        } else if let last = segments.last {
            let s = Int(last.endOffsetMs / 1000)
            txt += "Duration: \(s / 60)m \(s % 60)s\n"
        }
        let spaceName = meeting.spaceId.replacingOccurrences(of: "space-", with: "").capitalized
        txt += "Space:    \(spaceName)\n"

        // Unique participants
        let participants = Array(Set(segments.map { $0.speakerLabel })).sorted()
        if !participants.isEmpty {
            txt += "Speakers: \(participants.joined(separator: ", "))\n"
        }
        txt += "================================================================================\n\n"

        // Executive Summary if present
        if let sum = summary {
            if !sum.overview.isEmpty {
                txt += "--- EXECUTIVE SUMMARY ---\n"
                txt += "\(sum.overview)\n\n"
            }
            if !sum.keyPoints.isEmpty {
                txt += "--- KEY DISCUSSION POINTS ---\n"
                for pt in sum.keyPoints {
                    txt += "• \(pt)\n"
                }
                txt += "\n"
            }
            if !sum.decisions.isEmpty {
                txt += "--- CONFIRMED DECISIONS ---\n"
                for d in sum.decisions {
                    txt += "• \(d.title): \(d.rationale)\n"
                }
                txt += "\n"
            }
            if !sum.actionItems.isEmpty {
                txt += "--- ACTION ITEMS ---\n"
                for a in sum.actionItems {
                    let assignee = a.assignee?.isEmpty == false ? " [\(a.assignee!)]" : ""
                    let due = a.dueDate != nil ? " (Due: \(a.dueDate!))" : ""
                    txt += "• [ ]\(assignee) \(a.task)\(due)\n"
                }
                txt += "\n"
            }
        }

        // Full Chronological Transcript
        txt += "--- TRANSCRIPT ---\n"
        if segments.isEmpty {
            txt += "(No spoken audio segments recorded)\n"
        } else {
            for seg in segments {
                let timeStr = formatTimeOffsetMs(seg.startOffsetMs)
                txt += "[\(timeStr)] \(seg.speakerLabel): \(seg.text)\n"
            }
        }
        txt += "\n================================================================================\n"
        txt += "Generated by Sidebrief (https://sidebrief.tkoresearch.com)\n"
        return txt
    }

    // MARK: - Structured JSON (.json) Export

    public func generateJSONData(
        meeting: Meeting,
        segments: [TranscriptSegment],
        summary: MeetingSummary? = nil
    ) -> Data? {
        let participants = Array(Set(segments.map { $0.speakerLabel })).sorted()
        var payload: [String: Any] = [
            "schemaVersion": "1.0",
            "generator": "Sidebrief macOS",
            "exportedAt": Date().ISO8601Format(),
            "meeting": [
                "id": meeting.id,
                "title": meeting.title,
                "spaceId": meeting.spaceId,
                "state": meeting.state.rawValue,
                "createdAt": meeting.createdAt.ISO8601Format(),
                "actualStartTime": meeting.actualStartTime?.ISO8601Format() ?? "",
                "actualEndTime": meeting.actualEndTime?.ISO8601Format() ?? "",
                "participants": participants,
                "totalPromptTokens": meeting.totalPromptTokens,
                "totalCompletionTokens": meeting.totalCompletionTokens,
                "estimatedCostUSD": meeting.estimatedCostUSD
            ],
            "transcript": segments.map { [
                "id": $0.id,
                "speaker": $0.speakerLabel,
                "text": $0.text,
                "startOffsetMs": $0.startOffsetMs,
                "endOffsetMs": $0.endOffsetMs,
                "formattedTime": formatTimeOffsetMs($0.startOffsetMs),
                "trackId": $0.trackId
            ]}
        ]

        if let sum = summary {
            payload["summary"] = [
                "overview": sum.overview,
                "keyPoints": sum.keyPoints,
                "decisions": sum.decisions.map { ["title": $0.title, "rationale": $0.rationale, "status": $0.status] },
                "actionItems": sum.actionItems.map { ["task": $0.task, "assignee": $0.assignee ?? "", "dueDate": $0.dueDate ?? ""] }
            ]
        }

        return try? JSONSerialization.data(withJSONObject: payload, options: [.prettyPrinted, .sortedKeys])
    }

    // MARK: - Formatted PDF (.pdf) Export

    public func generatePDFData(
        meeting: Meeting,
        segments: [TranscriptSegment],
        summary: MeetingSummary? = nil
    ) -> Data? {
        let pdfData = NSMutableData()
        guard let consumer = CGDataConsumer(data: pdfData as CFMutableData) else { return nil }

        let pageWidth: CGFloat = 612
        let pageHeight: CGFloat = 792
        let margin: CGFloat = 54
        let contentWidth = pageWidth - (margin * 2)
        var mediaBox = CGRect(x: 0, y: 0, width: pageWidth, height: pageHeight)

        guard let ctx = CGContext(consumer: consumer, mediaBox: &mediaBox, nil) else { return nil }

        var currentPage = 1
        var currentY: CGFloat = margin

        func startPage() {
            ctx.beginPDFPage(nil)
            ctx.saveGState()
            ctx.translateBy(x: 0, y: pageHeight)
            ctx.scaleBy(x: 1.0, y: -1.0)
            let gc = NSGraphicsContext(cgContext: ctx, flipped: true)
            NSGraphicsContext.current = gc
            currentY = margin
        }

        func endPage() {
            // Draw Footer
            let footerAttr: [NSAttributedString.Key: Any] = [
                .font: NSFont.systemFont(ofSize: 9),
                .foregroundColor: NSColor.secondaryLabelColor
            ]
            let footerText = "Sidebrief Executive Meeting Journal  •  Page \(currentPage)"
            let footerStr = NSAttributedString(string: footerText, attributes: footerAttr)
            footerStr.draw(at: CGPoint(x: margin, y: pageHeight - margin + 10))

            // Footer divider rule
            ctx.setStrokeColor(NSColor.separatorColor.cgColor)
            ctx.setLineWidth(0.5)
            ctx.move(to: CGPoint(x: margin, y: pageHeight - margin + 4))
            ctx.addLine(to: CGPoint(x: pageWidth - margin, y: pageHeight - margin + 4))
            ctx.strokePath()

            ctx.restoreGState()
            ctx.endPDFPage()
            currentPage += 1
        }

        startPage()

        // Page 1 Header
        let titleAttr: [NSAttributedString.Key: Any] = [
            .font: NSFont.boldSystemFont(ofSize: 20),
            .foregroundColor: NSColor.labelColor
        ]
        let titleStr = NSAttributedString(string: meeting.title.isEmpty ? "Meeting Transcript" : meeting.title, attributes: titleAttr)
        let titleBounds = titleStr.boundingRect(with: CGSize(width: contentWidth, height: 200), options: [.usesLineFragmentOrigin])
        titleStr.draw(in: CGRect(x: margin, y: currentY, width: contentWidth, height: titleBounds.height))
        currentY += titleBounds.height + 6

        // Subtitle / Date / Duration
        let dateStrText = (meeting.actualStartTime ?? meeting.createdAt).formatted(date: .long, time: .shortened)
        let durationText: String
        if let start = meeting.actualStartTime, let end = meeting.actualEndTime {
            let s = Int(end.timeIntervalSince(start))
            durationText = " • \(s / 60)m \(s % 60)s"
        } else if let last = segments.last {
            let s = Int(last.endOffsetMs / 1000)
            durationText = " • \(s / 60)m \(s % 60)s"
        } else {
            durationText = ""
        }
        let metaText = "\(dateStrText)\(durationText) • Space: \(meeting.spaceId.replacingOccurrences(of: "space-", with: "").capitalized)"
        let metaAttr: [NSAttributedString.Key: Any] = [
            .font: NSFont.systemFont(ofSize: 10, weight: .medium),
            .foregroundColor: NSColor.secondaryLabelColor
        ]
        let metaStr = NSAttributedString(string: metaText, attributes: metaAttr)
        metaStr.draw(at: CGPoint(x: margin, y: currentY))
        currentY += 22

        // Top divider
        ctx.setStrokeColor(NSColor.separatorColor.cgColor)
        ctx.setLineWidth(0.75)
        ctx.move(to: CGPoint(x: margin, y: currentY))
        ctx.addLine(to: CGPoint(x: pageWidth - margin, y: currentY))
        ctx.strokePath()
        currentY += 16

        // Executive Summary (if present)
        if let sum = summary, !sum.overview.isEmpty {
            let sumHeaderAttr: [NSAttributedString.Key: Any] = [
                .font: NSFont.boldSystemFont(ofSize: 12),
                .foregroundColor: NSColor.labelColor
            ]
            let sumHeader = NSAttributedString(string: "EXECUTIVE SUMMARY", attributes: sumHeaderAttr)
            sumHeader.draw(at: CGPoint(x: margin, y: currentY))
            currentY += 16

            let sumBodyAttr: [NSAttributedString.Key: Any] = [
                .font: NSFont.systemFont(ofSize: 10.5),
                .foregroundColor: NSColor.labelColor
            ]
            let sumBody = NSAttributedString(string: sum.overview, attributes: sumBodyAttr)
            let sumBounds = sumBody.boundingRect(with: CGSize(width: contentWidth, height: 400), options: [.usesLineFragmentOrigin])
            sumBody.draw(in: CGRect(x: margin, y: currentY, width: contentWidth, height: sumBounds.height))
            currentY += sumBounds.height + 14

            if !sum.decisions.isEmpty {
                let decHeader = NSAttributedString(string: "CONFIRMED DECISIONS:", attributes: [
                    .font: NSFont.boldSystemFont(ofSize: 11),
                    .foregroundColor: NSColor.labelColor
                ])
                decHeader.draw(at: CGPoint(x: margin, y: currentY))
                currentY += 15

                for d in sum.decisions {
                    let dText = "• \(d.title): \(d.rationale)"
                    let dStr = NSAttributedString(string: dText, attributes: [
                        .font: NSFont.systemFont(ofSize: 10),
                        .foregroundColor: NSColor.labelColor
                    ])
                    let dBounds = dStr.boundingRect(with: CGSize(width: contentWidth, height: 200), options: [.usesLineFragmentOrigin])
                    dStr.draw(in: CGRect(x: margin, y: currentY, width: contentWidth, height: dBounds.height))
                    currentY += dBounds.height + 6
                }
                currentY += 10
            }

            ctx.setStrokeColor(NSColor.separatorColor.cgColor)
            ctx.setLineWidth(0.5)
            ctx.move(to: CGPoint(x: margin, y: currentY))
            ctx.addLine(to: CGPoint(x: pageWidth - margin, y: currentY))
            ctx.strokePath()
            currentY += 16
        }

        // Transcript Header
        let trHeader = NSAttributedString(string: "MEETING TRANSCRIPT", attributes: [
            .font: NSFont.boldSystemFont(ofSize: 12),
            .foregroundColor: NSColor.labelColor
        ])
        trHeader.draw(at: CGPoint(x: margin, y: currentY))
        currentY += 18

        // Transcript items
        for seg in segments {
            let isYou = (seg.speakerLabel == "You")
            let timeStr = formatTimeOffsetMs(seg.startOffsetMs)
            let headerText = "\(seg.speakerLabel) [\(timeStr)]"

            let speakerAttr: [NSAttributedString.Key: Any] = [
                .font: NSFont.boldSystemFont(ofSize: 10.5),
                .foregroundColor: isYou ? NSColor.systemBlue : NSColor.systemPurple
            ]
            let speakerStr = NSAttributedString(string: headerText, attributes: speakerAttr)
            let speakerBounds = speakerStr.boundingRect(with: CGSize(width: contentWidth, height: 40), options: [.usesLineFragmentOrigin])

            let bodyAttr: [NSAttributedString.Key: Any] = [
                .font: NSFont.systemFont(ofSize: 10),
                .foregroundColor: NSColor.labelColor
            ]
            let bodyStr = NSAttributedString(string: seg.text, attributes: bodyAttr)
            let bodyBounds = bodyStr.boundingRect(with: CGSize(width: contentWidth, height: 600), options: [.usesLineFragmentOrigin])

            let totalItemHeight = speakerBounds.height + bodyBounds.height + 10

            // Check if fits on current page
            if currentY + totalItemHeight > pageHeight - margin - 30 {
                endPage()
                startPage()
            }

            speakerStr.draw(in: CGRect(x: margin, y: currentY, width: contentWidth, height: speakerBounds.height))
            currentY += speakerBounds.height + 3

            bodyStr.draw(in: CGRect(x: margin, y: currentY, width: contentWidth, height: bodyBounds.height))
            currentY += bodyBounds.height + 8
        }

        endPage()
        ctx.closePDF()

        return pdfData as Data
    }

    // MARK: - Save Dialog Helper

    @MainActor
    public func exportWithSavePanel(
        filename: String,
        fileExtension: String,
        data: Data,
        completion: (@Sendable @MainActor (URL?) -> Void)? = nil
    ) {
        let savePanel = NSSavePanel()
        let sanitized = filename.replacingOccurrences(of: "/", with: "-").trimmingCharacters(in: .whitespacesAndNewlines)
        let base = sanitized.isEmpty ? "Meeting_Transcript" : sanitized
        savePanel.nameFieldStringValue = "\(base).\(fileExtension)"
        savePanel.canCreateDirectories = true

        savePanel.begin { result in
            if result == .OK, let url = savePanel.url {
                try? data.write(to: url)
                completion?(url)
            } else {
                completion?(nil)
            }
        }
    }

    @MainActor
    public func exportWithSavePanel(
        filename: String,
        fileExtension: String,
        textContent: String,
        completion: (@Sendable @MainActor (URL?) -> Void)? = nil
    ) {
        if let data = textContent.data(using: .utf8) {
            exportWithSavePanel(filename: filename, fileExtension: fileExtension, data: data, completion: completion)
        }
    }

    // MARK: - Helper

    public func formatTimeOffsetMs(_ ms: Int64) -> String {
        let totalSeconds = max(0, ms / 1000)
        let hours = totalSeconds / 3600
        let minutes = (totalSeconds % 3600) / 60
        let seconds = totalSeconds % 60
        if hours > 0 {
            return String(format: "%02d:%02d:%02d", hours, minutes, seconds)
        } else {
            return String(format: "%02d:%02d", minutes, seconds)
        }
    }
}
